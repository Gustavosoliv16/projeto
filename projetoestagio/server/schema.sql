CREATE TABLE IF NOT EXISTS SETOR (
  ID_SETOR INTEGER PRIMARY KEY AUTOINCREMENT,
  NOME_SETOR TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS USUARIOS (
  ID_USUARIOS INTEGER PRIMARY KEY AUTOINCREMENT,
  NOME_USUARIO TEXT NOT NULL,
  CPF TEXT NOT NULL UNIQUE,
  EMAIL TEXT NOT NULL UNIQUE,
  TIPO_USUARIO TEXT NOT NULL,
  SENHA TEXT NOT NULL,
  ID_SETOR INTEGER,
  DEPARTAMENTO TEXT,
  FOREIGN KEY (ID_SETOR) REFERENCES SETOR (ID_SETOR)
);

CREATE TABLE IF NOT EXISTS TIPO_SERVICO (
  ID_SERVICO INTEGER PRIMARY KEY AUTOINCREMENT,
  NOME_SERVICO TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS SOLICITACOES (
  ID_SOLICITACAO INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_USUARIO_SOLICITANTE INTEGER NOT NULL,
  ID_USUARIO_RESPONSAVEL INTEGER,
  ID_SERVICO INTEGER,
  STATUS TEXT NOT NULL DEFAULT 'ABERTA',
  DATA_CRIACAO TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DATA_CONCLUSAO TEXT,
  PATRIMONIO TEXT,
  DEFEITO_RELATADO TEXT NOT NULL,
  DEFEITO_ENCONTRADO TEXT,
  FOREIGN KEY (ID_USUARIO_SOLICITANTE) REFERENCES USUARIOS (ID_USUARIOS),
  FOREIGN KEY (ID_USUARIO_RESPONSAVEL) REFERENCES USUARIOS (ID_USUARIOS),
  FOREIGN KEY (ID_SERVICO) REFERENCES TIPO_SERVICO (ID_SERVICO)
);

CREATE TABLE IF NOT EXISTS PECAS (
  ID_PECA INTEGER PRIMARY KEY AUTOINCREMENT,
  NOME TEXT NOT NULL,
  DESCRICAO TEXT,
  MODELO TEXT,
  MARCA TEXT,
  FORNECEDOR TEXT,
  PATRIMONIO TEXT,
  ID_SETOR INTEGER,
  FOREIGN KEY (ID_SETOR) REFERENCES SETOR (ID_SETOR)
);

CREATE TABLE IF NOT EXISTS ESTOQUE_PECAS (
  ID_PECA INTEGER PRIMARY KEY,
  QUANTIDADE INTEGER NOT NULL DEFAULT 0 CHECK (QUANTIDADE >= 0),
  FOREIGN KEY (ID_PECA) REFERENCES PECAS (ID_PECA) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SOLICITACAO_PECAS (
  ID_SOLICITACAO INTEGER NOT NULL,
  ID_PECA INTEGER NOT NULL,
  QUANTIDADE_USADA INTEGER NOT NULL CHECK (QUANTIDADE_USADA > 0),
  PRIMARY KEY (ID_SOLICITACAO, ID_PECA),
  FOREIGN KEY (ID_SOLICITACAO) REFERENCES SOLICITACOES (ID_SOLICITACAO),
  FOREIGN KEY (ID_PECA) REFERENCES PECAS (ID_PECA)
);

CREATE TABLE IF NOT EXISTS MOVIMENTACAO_ESTOQUE (
  ID_MOVIMENTACAO INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_PECA INTEGER NOT NULL,
  QUANTIDADE INTEGER NOT NULL,
  TIPO TEXT NOT NULL,
  DATA_MOVIMENTACAO TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (ID_PECA) REFERENCES PECAS (ID_PECA)
);

CREATE TABLE IF NOT EXISTS HISTORICO_SOLICITACOES (
  ID_HISTORICO INTEGER PRIMARY KEY AUTOINCREMENT,
  ID_SOLICITACAO INTEGER,
  ID_USUARIO INTEGER,
  STATUS_ANTERIOR TEXT,
  STATUS_NOVO TEXT,
  DESCRICAO TEXT,
  DATA_ALTERACAO TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (ID_SOLICITACAO) REFERENCES SOLICITACOES (ID_SOLICITACAO),
  FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIOS)
);

CREATE INDEX IF NOT EXISTS IDX_USUARIOS_SETOR ON USUARIOS (ID_SETOR);
CREATE INDEX IF NOT EXISTS IDX_SOLICITACOES_SOLICITANTE ON SOLICITACOES (ID_USUARIO_SOLICITANTE);
CREATE INDEX IF NOT EXISTS IDX_SOLICITACOES_STATUS ON SOLICITACOES (STATUS);
CREATE INDEX IF NOT EXISTS IDX_PECAS_SETOR ON PECAS (ID_SETOR);
